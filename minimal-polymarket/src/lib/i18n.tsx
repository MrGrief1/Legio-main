const statusTranslationKeys: Record<MarketStatus, string> = {
  open: 'admin.status.open',
  paused: 'admin.status.paused',
  resolved: 'admin.status.resolved',
  canceled: 'admin.status.canceled',
};

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'ru';

  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'ru';
}

function translate(language: Language, key: string, params: TranslationParams = {}) {
  const template = translations[language][key] ?? translations.ru[key] ?? key;

  return template.replace(/\{(\w+)\}/g, (_, paramName: string) => (
    params[paramName] === undefined ? `{${paramName}}` : String(params[paramName])
  ));
}

export function getCategoryLabel(category: string, language: Language) {
  return categoryTranslations[language][category] ?? category;
}

export function getStatusLabel(status: MarketStatus, language: Language) {
  return translate(language, statusTranslationKeys[status]);
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: locales[language],
    setLanguage: setCurrentLanguage,
    toggleLanguage: () => setCurrentLanguage((current) => (current === 'ru' ? 'en' : 'ru')),
    t: (key, params) => translate(language, key, params),
    categoryLabel: (category) => getCategoryLabel(category, language),
    statusLabel: (status) => getStatusLabel(status, language),
    outcomeLabel: (outcome) => translate(language, outcome === 'YES' ? 'common.yes' : 'common.no'),
    tradeSideLabel: (side) => translate(language, side === 'BUY' ? 'common.bought' : 'common.sold'),
  }), [language]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }

  return context;
}
